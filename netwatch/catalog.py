@dataclass(frozen=True)
class EventInfo:
    log: str
    provider: str
    id: int
    level: str
    title: str
    meaning: str          # что произошло
    action: str           # что делать
    fields: tuple = ()    # (имя поля события, подпись, расшифровка)
    failures_only: bool = False  # брать только неудачные (событие пишется и при успехе)

    @property
    def key(self):
        return (self.log, self.provider.lower(), self.id)


