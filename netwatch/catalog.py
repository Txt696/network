def describe(event):
    """Название, важность и главное из события человеческим языком."""
    data = event.get("data") or {}
    info = lookup(event.get("log"), event.get("provider"), event.get("id", 0))
    if info is None:
        level = WINDOWS_LEVELS.get(event.get("level"), INFO)
        return {"title": "%s, событие %s" % (event.get("provider"), event.get("id")),
                "severity": level, "meaning": "", "action": "",
                "summary": first_line(event.get("message"))}
    summary = []
    for names, label, decoder in info.fields:
        value = next((data.get(name) for name in names.split("|")
                      if data.get(name) not in (None, "", "-", "0x0")), "")
        if value:
            summary.append([label, DECODERS[decoder](value) if decoder else value])
    severity = info.level
    if info.fields is GROUP_FIELDS and data.get("TargetUserName", "").lower() in PRIVILEGED_GROUPS \
            and info.level == WARNING:
        severity = CRITICAL
    return {"title": info.title, "severity": severity, "meaning": info.meaning,
            "action": info.action,
            "summary": summary or first_line(event.get("message"))}


def first_line(message, limit=300):
    for line in (message or "").splitlines():
        if line.strip():
            return line.strip()[:limit]
    return ""


