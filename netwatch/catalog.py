def _code(value, table):
    code = (value or "").strip().lower()
    return "%s (%s)" % (table[code], value) if code in table else value


def _ip(value):
    value = (value or "").strip()
    return value[7:] if value.startswith("::ffff:") else value


DECODERS = {
    "ntstatus": lambda value: _code(value, NTSTATUS),
    "kerberos": lambda value: _code(value, KERBEROS),
    "logon": lambda value: LOGON_TYPES.get(value, value),
    "ip": _ip,
}

